export type IconName = keyof typeof ICONS;

export function Icon({ name, size = 20, className }: { name: IconName; size?: number; className?: string }) {
  const Glyph = ICONS[name];
  // Stop is a solid square, drawn smaller than a full-size glyph so it sits level with the send arrow.
  if (name === "stop")
    return (
      <Glyph
        size={Math.round(size * 0.65)}
        strokeWidth={2}
        fill="currentColor"
        aria-hidden="true"
        className={className ? `icon ${className}` : "icon"}
      />
    );
  return (
    <Glyph size={size} strokeWidth={1.9} aria-hidden="true" className={className ? `icon ${className}` : "icon"} />
  );
}
