// `rei init` (containers/init.sh calls it; setup runs it): creates, once, what the containers share through one file,
// .secrets/secrets.env (mode 0600) next to the compose files:
//   REI_STANDIN                  Rei's own token for the gateway: the control plane presents it, and it is the one caller
//                                that may use every gateway route. It only works against the gateway, which Rei reaches
//                                over a private network. Other services get their own tokens: rei callers.
//   GARAGE_*                     the object store's RPC secret, admin token and the single S3 key (and the bucket name).
//   QDRANT__SERVICE__API_KEY     the retrieval service's API key.
//   REI_EVENTS_KEY               the key (64 hex characters) the control plane encrypts event sources' secrets with
//                                (docs/events.md). Losing it makes those secrets unreadable; rotate them with rei sources.
// The names are the ones Garage and Qdrant read. The two compose files interpolate the file into each service's own
// environment, so a service gets only the variables it uses (compose needs --env-file for it; the CLI and the smoke
// scripts pass it). It also creates .env, empty, if it is absent; keyless Exa needs no configuration.
//
// A value that exists is never regenerated: that would orphan the data written with it. A file that lost a line gets the
// missing variable and keeps the others.
//
// It also creates, if missing, the external Docker volumes Dodai and Rei keep their data in (<REI_PROJECT or rei>_gateway-data,
// _reader-data, _garage-meta, _garage-data, _qdrant-data, _qdrant-snapshots). They are external so that no `down -v` of
// any project can delete them; compose does not create them, so skipping this fails the first `up`. Volumes that already
// exist, from a stack made before they were external, are left as they are.
//
// Everything else is configured in the web app (model account, embeddings, web search providers and their keys).
//
// An installation made before secrets.env (one file per value: standin, garage/*, qdrant-api-key, qdrant.env, and a search/
// folder of provider keys) is migrated in place: the same values move into secrets.env, so the data written with them
// stays readable, and the old files are removed once secrets.env holds all of them.
import { randomBytes } from "node:crypto";
import { join } from "node:path";
import type { Ctx } from "./ctx.ts";
import { EXTERNAL_VOLUMES, volumeName } from "./ctx.ts";

/** Every variable secrets.env must carry, in the order the file lists them (GARAGE_DEFAULT_BUCKET is a fixed name). */
export const SECRET_VARS = [
  "REI_STANDIN",
  "GARAGE_RPC_SECRET",
  "GARAGE_ADMIN_TOKEN",
  "GARAGE_DEFAULT_ACCESS_KEY",
  "GARAGE_DEFAULT_SECRET_KEY",
  "QDRANT__SERVICE__API_KEY",
  "REI_EVENTS_KEY",
] as const;

type SecretVar = (typeof SECRET_VARS)[number];

const hex = (bytes: number): string => randomBytes(bytes).toString("hex");

/** Where the old layout kept each value (relative to .secrets/), and how a new one is made. */
const SOURCES: Record<SecretVar, { legacy?: string; fresh: () => string }> = {
  // Base64 of 32 random bytes without padding, + or /: letters and digits only, about 43 of them.
  REI_STANDIN: { legacy: "standin", fresh: () => randomBytes(32).toString("base64").replace(/[=+/]/g, "") },
  GARAGE_RPC_SECRET: { legacy: "garage/rpc-secret", fresh: () => hex(32) },
  GARAGE_ADMIN_TOKEN: { legacy: "garage/admin-token", fresh: () => hex(16) },
  GARAGE_DEFAULT_ACCESS_KEY: { legacy: "garage/access-key", fresh: () => `GK${hex(16)}` },
  GARAGE_DEFAULT_SECRET_KEY: { legacy: "garage/secret-key", fresh: () => hex(32) },
  QDRANT__SERVICE__API_KEY: { legacy: "qdrant-api-key", fresh: () => hex(32) },
  REI_EVENTS_KEY: { fresh: () => hex(32) },
};

/** The old layout's files, removed once secrets.env holds every value. */
const LEGACY_FILES = [
  "garage/rpc-secret",
  "garage/admin-token",
  "garage/access-key",
  "garage/secret-key",
  "garage/default-keys.env",
  "garage/garage.toml",
  "qdrant-api-key",
  "qdrant.env",
  "standin",
];

/** The value of the first `VAR=` line, as `sed -n "s/^VAR=//p" | head -n 1` read it; "" when there is none. */
function firstValue(text: string, name: string): string {
  for (const line of text.split("\n")) if (line.startsWith(`${name}=`)) return line.slice(name.length + 1);
  return "";
}

/** Whether some line sets the variable to something (`grep -q "^VAR=."`). */
const hasValue = (text: string, name: string): boolean =>
  text.split("\n").some((line) => line.startsWith(`${name}=`) && line.length > name.length + 1);

function secretsText(values: Record<SecretVar, string>): string {
  return `# Generated by rei init (containers/init.sh); never regenerated over an existing installation (that would orphan the
# data written with these). Garage gets the GARAGE_* variables, Qdrant QDRANT__SERVICE__API_KEY, the gateway REI_STANDIN, and the
# control plane REI_STANDIN, REI_EVENTS_KEY, the S3 key and the Qdrant key. GARAGE_DEFAULT_* also bootstrap the bucket and key on first start.
REI_STANDIN=${values.REI_STANDIN}
GARAGE_RPC_SECRET=${values.GARAGE_RPC_SECRET}
GARAGE_ADMIN_TOKEN=${values.GARAGE_ADMIN_TOKEN}
GARAGE_DEFAULT_BUCKET=rei-files
GARAGE_DEFAULT_ACCESS_KEY=${values.GARAGE_DEFAULT_ACCESS_KEY}
GARAGE_DEFAULT_SECRET_KEY=${values.GARAGE_DEFAULT_SECRET_KEY}
QDRANT__SERVICE__API_KEY=${values.QDRANT__SERVICE__API_KEY}
REI_EVENTS_KEY=${values.REI_EVENTS_KEY}
`;
}

/**
 * Makes .env, secrets.env and the external volumes, keeping whatever exists. Every line it prints names a path or a
 * volume, never a value. Returns 0, or 1 when a volume could not be created.
 */
export async function initSecrets(
  ctx: Ctx,
  log: (line: string) => void = (line) => ctx.out.line(line),
): Promise<number> {
  const { host } = ctx;
  const dir = join(ctx.envDir, ".secrets");
  host.mkdirp(dir, 0o755);
  const envFile = join(ctx.envDir, ".env");
  if (!host.stat(envFile)) {
    host.writeText(envFile, "", 0o644);
    log(`created ${envFile}`);
  }

  // ---- the shared secrets
  const secretsFile = join(dir, "secrets.env");
  const current = host.readText(secretsFile) ?? "";
  if (SECRET_VARS.some((name) => !hasValue(current, name))) {
    // The value already in secrets.env, else the one the old layout kept, else a new one.
    const values = Object.fromEntries(
      SECRET_VARS.map((name) => {
        const existing = firstValue(current, name);
        if (existing) return [name, existing];
        const legacy = SOURCES[name].legacy;
        const kept =
          legacy && (host.stat(join(dir, legacy))?.size ?? 0) > 0 ? host.readText(join(dir, legacy)) : undefined;
        return [name, kept !== undefined ? kept.replace(/\n/g, "") : SOURCES[name].fresh()];
      }),
    ) as Record<SecretVar, string>;
    const tmp = `${secretsFile}.tmp`;
    host.writeText(tmp, secretsText(values), 0o600);
    host.rename(tmp, secretsFile);
    log(`created ${secretsFile}`);
  }

  // Retire the old layout, but only once secrets.env demonstrably carries what it held.
  const written = host.readText(secretsFile) ?? "";
  if (SECRET_VARS.every((name) => hasValue(written, name))) {
    for (const old of LEGACY_FILES) {
      const path = join(dir, old);
      if (host.stat(path)) {
        host.remove(path);
        log(`removed ${path} (its value is in secrets.env)`);
      }
    }
    host.removeDir(join(dir, "garage"));
  }
  // Search provider keys are saved in the web app now; the gateway no longer reads this folder.
  const search = join(dir, "search");
  if (host.list(search) !== undefined) {
    if (host.removeDir(search)) log(`removed ${search} (empty; web search is configured in the web app)`);
    else
      log(
        `note: ${search} is no longer read. Enter those keys in the web app (Settings, web search), then delete the folder.`,
      );
  }

  // ---- the external volumes. A machine without docker can still have its secrets made.
  let code = 0;
  for (const name of EXTERNAL_VOLUMES) {
    const volume = volumeName(ctx, name);
    const found = await ctx.runner.run("docker", ["volume", "inspect", volume], { timeoutMs: 30_000 });
    if (found.code === 127) {
      log("note: docker not found; the storage volumes were not created (run this again where docker runs)");
      break;
    }
    if (found.code === 0) continue;
    const made = await ctx.runner.run("docker", ["volume", "create", volume], { timeoutMs: 30_000 });
    if (made.code === 0) log(`created volume ${volume}`);
    else {
      log(`could not create volume ${volume}: ${made.stderr.trim().split("\n", 1)[0] || `exit ${made.code}`}`);
      code = 1;
    }
  }
  return code;
}
