import androidx.compose.ui.unit.dp
import dev.rei.android.ui.icons.ReiIcons

/** Says what goes here and how it gets filled ("Files you upload or that agents save appear here."). */
@Composable
fun EmptyState(
    icon: ImageVector,
    title: String,
    modifier: Modifier = Modifier,
    body: String? = null,
    action: (@Composable () -> Unit)? = null,
) {
    Column(
        modifier.fillMaxWidth().padding(horizontal = 32.dp, vertical = 40.dp),
        horizontalAlignment = Alignment.CenterHorizontally,
        verticalArrangement = Arrangement.spacedBy(8.dp),
    ) {
        Icon(icon, contentDescription = null, tint = MaterialTheme.colorScheme.onSurfaceVariant, modifier = Modifier.size(36.dp))
        Text(title, style = MaterialTheme.typography.titleMedium, textAlign = TextAlign.Center)
        if (body != null) {
            Text(
                body,
                style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
                textAlign = TextAlign.Center,
            )
        }
        if (action != null) Column(Modifier.padding(top = 8.dp), content = { action() })
    }
}

@ReiPreviews
@Composable
private fun EmptyStatePreview() = ReiPreviewSurface {
    EmptyState(ReiIcons.Library, "Nothing in the Library yet", body = "Files you upload or that agents save appear here.")
}
