// Uploads over the old 25 MiB limit go through end to end without the server holding the file: the request is read as
// a stream, staged on disk, put into the object store as a stream, and read back as a stream.
//
// The size is 40 MiB by default. REI_TEST_UPLOAD_MIB raises it (for example to 1024) for a manual run.
import { createHash } from "node:crypto";
import { readdirSync } from "node:fs";
import { join } from "node:path";
import type { Attachment, LibraryFile } from "@rei/protocol";
import { afterEach, describe, expect, it } from "vitest";
import { FolderFileObjectStore } from "../src/node/folder-object-store.ts";
import type { PutInput } from "../src/storage/file-object-store.ts";
import { startSignedIn, type TestServer } from "./helpers/server.ts";
import { chat } from "./helpers/sessions.ts";

const MIB = 1024 * 1024;
const SIZE = Number(process.env.REI_TEST_UPLOAD_MIB ?? 40) * MIB;
const BOUNDARY = "----rei-large-upload";

/** Records how each put arrived, and how much the process held while it did. */
class RecordingStore extends FolderFileObjectStore {
  puts: { kind: "bytes" | "stream"; byteLength: number }[] = [];
  override async put(input: PutInput): Promise<void> {
    this.puts.push(
      "bytes" in input
        ? { kind: "bytes", byteLength: input.bytes.byteLength }
        : { kind: "stream", byteLength: input.byteLength },
    );
    return super.put(input);
  }
}

/** A deterministic, incompressible chunk for position `i`. */
function chunkAt(i: number): Uint8Array {
  const out = new Uint8Array(MIB);
  let seed = 0;
  for (let block = 0; block < MIB; block += 32) {
    const digest = createHash("sha256").update(`${i}:${block}:${seed}`).digest();
    out.set(digest, block);
    seed = digest[0]!;
  }
  return out;
}

/** A multipart request body of `size` generated bytes, made as it is read, plus the file's sha256 and peak memory. */
function generated(size: number, name: string) {
  const hash = createHash("sha256");
  const head = new TextEncoder().encode(
    `--${BOUNDARY}\r\nContent-Disposition: form-data; name="file"; filename="${name}"\r\nContent-Type: application/octet-stream\r\n\r\n`,
  );
  const tail = new TextEncoder().encode(`\r\n--${BOUNDARY}--\r\n`);
  const chunks = Math.ceil(size / MIB);
  const stats = { peakHeld: 0, baseline: process.memoryUsage().arrayBuffers };
  let next = -1;
  const body = new ReadableStream<Uint8Array>(
    {
      pull(controller) {
        stats.peakHeld = Math.max(stats.peakHeld, process.memoryUsage().arrayBuffers - stats.baseline);
        if (next === -1) controller.enqueue(head);
        else if (next < chunks) {
          const chunk = chunkAt(next).subarray(0, Math.min(MIB, size - next * MIB));
          hash.update(chunk);
          controller.enqueue(chunk);
        } else if (next === chunks) controller.enqueue(tail);
        else controller.close();
        next++;
      },
    },
    { highWaterMark: 0 },
  );
  return {
    body,
    stats,
    length: head.length + size + tail.length,
    sha256: () => hash.digest("hex"),
  };
}

async function post(s: TestServer, path: string, size: number, name: string) {
  const upload = generated(size, name);
  const response = await s.client.fetcher(path, {
    method: "POST",
    body: upload.body,
    duplex: "half",
    headers: {
      cookie: `rei_session=${s.client.cookie}`,
      "x-rei": "1",
      "content-type": `multipart/form-data; boundary=${BOUNDARY}`,
      "content-length": String(upload.length),
    },
  } as RequestInit);
  return { response, upload };
}

async function digest(response: Response): Promise<{ sha256: string; bytes: number }> {
  const hash = createHash("sha256");
  let bytes = 0;
  const reader = response.body!.getReader();
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    bytes += value.byteLength;
    hash.update(value);
  }
  return { sha256: hash.digest("hex"), bytes };
}

let server: TestServer | undefined;
afterEach(async () => {
  await server?.destroy();
  server = undefined;
});

describe("large uploads", () => {
  it("streams a chat attachment over the old limit in and out without holding it", async () => {
    const store = new RecordingStore(join(process.env.TMPDIR ?? "/tmp", `rei-large-${crypto.randomUUID()}`));
    server = await startSignedIn({ fileObjects: store });
    const s = server;
    const id = await chat(s);

    const { response, upload } = await post(s, `/api/sessions/${id}/attachments`, SIZE, "big.bin");
    expect(response.status).toBe(200);
    const attachment: Attachment = (await response.json()).attachment;
    expect(attachment.size).toBe(SIZE);
    // The put was handed a stream of the staged file, never the whole file as bytes.
    expect(store.puts).toEqual([{ kind: "stream", byteLength: expect.any(Number) }]);
    expect(store.puts[0]!.byteLength).toBeGreaterThan(SIZE);
    // The upload was not buffered: the process held far less than the file while the request was read.
    expect(upload.stats.peakHeld).toBeLessThan(Math.min(SIZE / 2, 24 * MIB));
    // The staged copy is gone once the upload is stored.
    expect(readdirSync(join(s.dir, "uploads"))).toEqual([]);

    const download = await s.client.fetcher(`/api/sessions/${id}/attachments/${attachment.id}`, {
      headers: { cookie: `rei_session=${s.client.cookie}` },
    });
    expect(download.status).toBe(200);
    expect(download.headers.get("content-length")).toBe(String(SIZE));
    expect(await digest(download)).toEqual({ sha256: upload.sha256(), bytes: SIZE });
  }, 180_000);

  it("streams a Library upload over the old limit and its download", async () => {
    const store = new RecordingStore(join(process.env.TMPDIR ?? "/tmp", `rei-large-${crypto.randomUUID()}`));
    server = await startSignedIn({ fileObjects: store });
    const s = server;
    const { response, upload } = await post(s, "/api/files", SIZE, "archive.bin");
    expect(response.status).toBe(200);
    const file: LibraryFile = (await response.json()).file;
    expect(file.current.size).toBe(SIZE);
    expect(store.puts.map((put) => put.kind)).toEqual(["stream"]);

    const download = await s.client.fetcher(`/api/files/${file.id}/versions/${file.current.versionId}/content`, {
      headers: { cookie: `rei_session=${s.client.cookie}` },
    });
    expect(download.status).toBe(200);
    expect(await digest(download)).toEqual({ sha256: upload.sha256(), bytes: SIZE });
  }, 180_000);

  it("refuses an upload that passes 1 GiB while it streams and keeps nothing", async () => {
    const store = new RecordingStore(join(process.env.TMPDIR ?? "/tmp", `rei-large-${crypto.randomUUID()}`));
    server = await startSignedIn({ fileObjects: store });
    const s = server;
    // No Content-Length is sent and the body never ends on its own: only the running count can stop it. Up to 1 GiB
    // lands in the spool on disk before the refusal, and is removed with it.
    const id = await chat(s);
    const zeros = new Uint8Array(MIB);
    let pulled = 0;
    let cancelled = false;
    const head = new TextEncoder().encode(
      `--${BOUNDARY}\r\nContent-Disposition: form-data; name="file"; filename="endless.bin"\r\n\r\n`,
    );
    const body = new ReadableStream<Uint8Array>(
      {
        pull(controller) {
          const chunk = pulled === 0 ? head : zeros;
          pulled += chunk.byteLength;
          controller.enqueue(chunk);
        },
        cancel() {
          cancelled = true;
        },
      },
      { highWaterMark: 0 },
    );
    const response = await s.client.fetcher(`/api/sessions/${id}/attachments`, {
      method: "POST",
      body,
      duplex: "half",
      headers: {
        cookie: `rei_session=${s.client.cookie}`,
        "x-rei": "1",
        "content-type": `multipart/form-data; boundary=${BOUNDARY}`,
      },
    } as RequestInit);
    expect(response.status).toBe(413);
    expect((await response.json()).error.message).toBe("Files can be at most 1 GiB.");
    expect(cancelled).toBe(true);
    expect(pulled).toBeLessThan(1024 * MIB + 70_000 + 2 * MIB);
    expect(store.puts).toEqual([]);
    expect(readdirSync(join(s.dir, "uploads"))).toEqual([]);
  }, 300_000);
});
