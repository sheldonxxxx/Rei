// Embeds the rei-knowledge skill's Markdown (src/skills/knowledge/) into a TypeScript module. The server's portable
// code cannot read files and Node cannot import .md, so the text ships as a string. Run `npm run build:skills -w
// @rei/server` after editing either file; a server test fails while the module is out of date.
import { readFileSync, writeFileSync } from "node:fs";

const DIR = new URL("../src/skills/knowledge/", import.meta.url);
const OUT = new URL("../src/skills/knowledge-files.generated.ts", import.meta.url);
const FILES = ["SKILL.md", "references/markdown.md"];

export function render(): string {
  const entries = FILES.map(
    (path) =>
      `  { path: ${JSON.stringify(path)}, content: ${JSON.stringify(readFileSync(new URL(path, DIR), "utf8"))} },`,
  );
  return [
    "// Generated by scripts/build-knowledge-skill.ts from src/skills/knowledge/. Do not edit.",
    "export const KNOWLEDGE_SKILL_FILES: { path: string; content: string }[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && new URL(import.meta.url).pathname === process.argv[1]) writeFileSync(OUT, render());
