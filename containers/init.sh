#!/bin/sh
# Creates, once, what the containers share through one file, containers/.secrets/secrets.env (mode 0600):
#   REI_STANDIN                  Rei's own token for the gateway: the control plane presents it, and it is the one caller
#                                that may use every gateway route. It only works against the gateway, which Rei reaches
#                                over a private network. Other services get their own tokens: ./rei callers.
#   GARAGE_*                     the object store's RPC secret, admin token and the single S3 key (and the bucket name).
#   QDRANT__SERVICE__API_KEY     the retrieval service's API key.
#   REI_EVENTS_KEY               the key (64 hex characters) the control plane encrypts event sources' secrets with
#                                (docs/events.md). Losing it makes those secrets unreadable; rotate them with ./rei sources.
# The names are the ones Garage and Qdrant read. The two compose files interpolate the file into each service's own environment, so
# a service gets only the variables it uses (compose needs --env-file for it; ./rei and the smoke scripts pass it).
#   .env            created empty if absent; keyless Exa needs no configuration.
# It also creates, if missing, the external Docker volumes Dodai and Rei keep their data in (<REI_PROJECT or rei>_gateway-data,
# _reader-data, _garage-meta, _garage-data, _qdrant-data, _qdrant-snapshots). They are external so that no `down -v` of
# any project can delete them; compose does not create them, so skipping this script fails the first `up`. Volumes that
# already exist, from a stack made before they were external, are left as they are.
#
# Everything else is configured in the web app (model account, embeddings, web search providers and their keys). Nothing
# here is committed: containers/.secrets/ is in .gitignore.
#
# An installation made before secrets.env (one file per value: standin, garage/*, qdrant-api-key, qdrant.env, and a search/
# folder of provider keys) is migrated in place: the same values move into secrets.env, so the data written with them
# stays readable, and the old files are removed once secrets.env holds all of them.
set -eu
dir="$(dirname "$0")/.secrets"
mkdir -p "$dir"
if [ ! -e "$(dirname "$0")/.env" ]; then
  : > "$(dirname "$0")/.env"
  echo "created $(dirname "$0")/.env"
fi
# ---- the shared secrets ---------------------------------------------------------------------------------
# Hex from the system entropy source (openssl is not a dependency of this script).
hex() { od -An -tx1 -N "$1" /dev/urandom | tr -d ' \n'; }
env_file="$dir/secrets.env"
legacy_garage="$dir/garage"

# value <VAR> <legacy file> <fresh>: the value already in secrets.env, else the one the old layout kept, else a new one.
value() {
  existing=""
  [ -f "$env_file" ] && existing=$(sed -n "s/^$1=//p" "$env_file" | head -n 1)
  if [ -n "$existing" ]; then printf '%s' "$existing"; return; fi
  if [ -s "$2" ]; then tr -d '\n' < "$2"; return; fi
  printf '%s' "$3"
}

# Whether any variable is missing: a first run, a migration, or a file that lost a line.
missing=""
for var in REI_STANDIN GARAGE_RPC_SECRET GARAGE_ADMIN_TOKEN GARAGE_DEFAULT_ACCESS_KEY GARAGE_DEFAULT_SECRET_KEY QDRANT__SERVICE__API_KEY REI_EVENTS_KEY; do
  grep -q "^$var=." "$env_file" 2>/dev/null || missing="$missing $var"
done
if [ -n "$missing" ]; then
  standin=$(value REI_STANDIN "$dir/standin" "$(head -c 32 /dev/urandom | base64 | tr -d '\n=+/')")
  rpc=$(value GARAGE_RPC_SECRET "$legacy_garage/rpc-secret" "$(hex 32)")
  admin=$(value GARAGE_ADMIN_TOKEN "$legacy_garage/admin-token" "$(hex 16)")
  access=$(value GARAGE_DEFAULT_ACCESS_KEY "$legacy_garage/access-key" "GK$(hex 16)")
  secret=$(value GARAGE_DEFAULT_SECRET_KEY "$legacy_garage/secret-key" "$(hex 32)")
  qdrant=$(value QDRANT__SERVICE__API_KEY "$dir/qdrant-api-key" "$(hex 32)")
  events=$(value REI_EVENTS_KEY /dev/null "$(hex 32)")
  tmp="$env_file.tmp"
  (umask 077 && cat > "$tmp" <<EOF
# Generated by containers/init.sh; never regenerated over an existing installation (that would orphan the data written
# with these). Garage gets the GARAGE_* variables, Qdrant QDRANT__SERVICE__API_KEY, the gateway REI_STANDIN, and the
# control plane REI_STANDIN, REI_EVENTS_KEY, the S3 key and the Qdrant key. GARAGE_DEFAULT_* also bootstrap the bucket and key on first start.
REI_STANDIN=$standin
GARAGE_RPC_SECRET=$rpc
GARAGE_ADMIN_TOKEN=$admin
GARAGE_DEFAULT_BUCKET=rei-files
GARAGE_DEFAULT_ACCESS_KEY=$access
GARAGE_DEFAULT_SECRET_KEY=$secret
QDRANT__SERVICE__API_KEY=$qdrant
REI_EVENTS_KEY=$events
EOF
  )
  mv "$tmp" "$env_file"
  chmod 600 "$env_file"
  echo "created $env_file"
fi

# Retire the old layout, but only once secrets.env demonstrably carries what it held.
complete=yes
for var in REI_STANDIN GARAGE_RPC_SECRET GARAGE_ADMIN_TOKEN GARAGE_DEFAULT_ACCESS_KEY GARAGE_DEFAULT_SECRET_KEY QDRANT__SERVICE__API_KEY REI_EVENTS_KEY; do
  grep -q "^$var=." "$env_file" 2>/dev/null || complete=no
done
if [ "$complete" = yes ]; then
  for old in "$legacy_garage/rpc-secret" "$legacy_garage/admin-token" "$legacy_garage/access-key" "$legacy_garage/secret-key" \
    "$legacy_garage/default-keys.env" "$legacy_garage/garage.toml" "$dir/qdrant-api-key" "$dir/qdrant.env" "$dir/standin"; do
    if [ -e "$old" ]; then
      rm -f "$old"
      echo "removed $old (its value is in secrets.env)"
    fi
  done
  rmdir "$legacy_garage" 2>/dev/null || true
fi
# Search provider keys are saved in the web app now; the gateway no longer reads this folder.
if [ -d "$dir/search" ]; then
  if rmdir "$dir/search" 2>/dev/null; then
    echo "removed $dir/search (empty; web search is configured in the web app)"
  else
    echo "note: $dir/search is no longer read. Enter those keys in the web app (Settings, web search), then delete the folder." >&2
  fi
fi

# ---- the external volumes -------------------------------------------------------------------------------
# docker is needed for them (and for everything else here), but a machine without it can still have its secrets made.
if command -v docker >/dev/null 2>&1; then
  for name in gateway-data reader-data garage-meta garage-data qdrant-data qdrant-snapshots; do
    volume="${REI_PROJECT:-rei}_$name"
    if ! docker volume inspect "$volume" >/dev/null 2>&1; then
      docker volume create "$volume" >/dev/null && echo "created volume $volume"
    fi
  done
else
  echo "note: docker not found; the storage volumes were not created (run this again where docker runs)" >&2
fi
exit 0
